// 生成内嵌 SVG 占位图（emoji + 淡色底），无需任何外部图片
function svgImg(emoji, bg) {
  const fill = bg || DEFAULT_COLOR;
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="240" height="240">'
    + '<rect width="240" height="240" fill="' + fill + '"/>'
    + '<text x="120" y="150" font-size="96" text-anchor="middle">' + emoji + '</text></svg>';
  return 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg);
}

// 快捷构造一条示例数据：category/area 用下标，保证任意场景配置都适配
function S(module, name, catIdx, areaIdx, location, time, desc, contact, status, emoji) {
  const category = CAT(catIdx);
  return {
    module: module, name: name, category: category, campus: A(areaIdx),
    location: location, time: time, desc: desc, contact: contact,
    status: status, image: svgImg(emoji, CATEGORY_COLORS[category])
  };
}

